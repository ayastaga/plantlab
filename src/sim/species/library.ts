/** Layer the published values over each profile and attach the citations. */
function applySourced(sp: SpeciesProfile): SpeciesProfile {
  const s = SOURCED[sp.id]
  if (!s) return { ...sp, confidence: 'low' }
  const o = s.overrides
  return {
    ...sp,
    ...(o as Partial<SpeciesProfile>),
    confidence: s.confidence,
    leaf: { ...sp.leaf, ...o.leaf },
    light: { ...sp.light, ...o.light },
    temperature: { ...sp.temperature, ...o.temperature },
    humidity: { ...sp.humidity, ...o.humidity },
    water: { ...sp.water, ...o.water },
    growth: { ...sp.growth, ...o.growth },
    starter: sp.starter,
    evidence: s.evidence,
  } as SpeciesProfile
}

const RANK = { high: 0, medium: 1, low: 2 }
/** Best-evidenced species first. */
export const LIBRARY: SpeciesProfile[] = RAW.map(applySourced).sort((a, b) => RANK[a.confidence] - RANK[b.confidence])
